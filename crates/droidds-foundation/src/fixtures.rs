//! CodexAstraUlt: Original synthetic instruction examples written for
//! DroidDS; these bytes, addresses and expected values come from no game.

use crate::memory::{Memory, DATA, EXTRA, START};
use crate::runner::Snapshot;
use zakuro_cpu::Cpu;

pub const CHECKPOINT: u32 = 42;

// CodexAstraUlt: Each fixture carries explicit discovery seeds and an independent
// expected end state. The absent-entry bytes are intentionally outside Program.
pub struct Fixture {
    pub name: &'static str,
    pub text: Vec<u8>,
    pub seeds: Vec<u32>,
    pub cpu: Cpu,
    pub memory: Memory,
    pub expected: Snapshot,
    pub fallback_steps: u64,
    // CodexAstraUlt: Exact route evidence for these tiny known fixtures prevents
    // a native-entry call or incidental fallback from masquerading as AOT proof.
    pub native_budget: u64,
    pub native_lookups: u64,
    pub thumb_entry: Option<u32>,
}

fn arm(words: &[u32]) -> Vec<u8> {
    words.iter().flat_map(|word| word.to_le_bytes()).collect()
}

fn thumb(halfwords: &[u16]) -> Vec<u8> {
    halfwords
        .iter()
        .flat_map(|word| word.to_le_bytes())
        .collect()
}

// CodexAstraUlt: Nonzero untouched registers, VFP bit patterns and data bytes
// expose accidental clobbers. NaN-shaped r6 is integer data and must stay exact.
fn initial(thumb: bool) -> (Cpu, Memory) {
    let mut cpu = Cpu::new();
    for (index, register) in cpu.regs.iter_mut().enumerate() {
        *register = 0x1357_0000 + index as u32;
    }
    cpu.regs[4] = DATA;
    cpu.regs[6] = 0x7fc0_0001;
    cpu.regs[13] = 0xef00;
    cpu.regs[15] = START;
    cpu.cpsr.thumb = thumb;
    cpu.cpsr.q = true;
    cpu.cpsr.ge = 0b0101;
    cpu.cp15.thread_id_ro = 0x4545_0000;
    for (index, register) in cpu.vfp.regs.iter_mut().enumerate() {
        *register = 0x3f00_0000 + index as u32;
    }
    (cpu, Memory::new())
}

// CodexAstraUlt: Expected snapshots are hand-derived from the listed instruction
// semantics, never generated by executing either side of the comparison.
pub fn fixtures() -> Vec<Fixture> {
    let (cpu, mut memory) = initial(false);
    let text = arm(&[
        0xe3a0_0007, // CodexAstraUlt: mov r0, #7.
        0xe3a0_7103, // CodexAstraUlt: mov r7, #0xc0000000 (rotated immediate).
        0xe3a0_1005, // CodexAstraUlt: mov r1, #5.
        0xe090_2001, // CodexAstraUlt: adds r2, r0, r1 -> 12, NZCV clear.
        0xe352_000c, // CodexAstraUlt: cmp r2, #12 -> Z and C set.
        0x03a0_3009, // CodexAstraUlt: moveq r3, #9 executes.
        0x13a0_3063, // CodexAstraUlt: movne r3, #99 does not execute.
        0xe584_2000, // CodexAstraUlt: str r2, [r4].
        0xe584_6004, // CodexAstraUlt: str r6, [r4, #4], preserving integer bits.
        0xe594_5000, // CodexAstraUlt: ldr r5, [r4].
        0xef00_002a, // CodexAstraUlt: svc #42 is a full-state checkpoint.
    ]);
    memory.load(START, &text);
    let mut expected_cpu = cpu.clone();
    expected_cpu.regs[0] = 7;
    expected_cpu.regs[1] = 5;
    expected_cpu.regs[2] = 12;
    expected_cpu.regs[3] = 9;
    expected_cpu.regs[5] = 12;
    expected_cpu.regs[7] = 0xc000_0000;
    expected_cpu.regs[15] = START + text.len() as u32;
    expected_cpu.cpsr.z = true;
    expected_cpu.cpsr.c = true;
    let mut expected_memory = memory.clone();
    expected_memory.load(DATA, &12u32.to_le_bytes());
    expected_memory.load(DATA + 4, &0x7fc0_0001u32.to_le_bytes());
    let arm_case = Fixture {
        name: "arm_integer_memory",
        text,
        seeds: vec![START],
        expected: Snapshot::capture(&expected_cpu, &expected_memory),
        cpu,
        memory,
        fallback_steps: 0,
        native_budget: 11,
        native_lookups: 0,
        thumb_entry: None,
    };

    let (cpu, mut memory) = initial(true);
    let text = thumb(&[
        0x2007, // CodexAstraUlt: movs r0, #7.
        0x2105, // CodexAstraUlt: movs r1, #5.
        0x1842, // CodexAstraUlt: adds r2, r0, r1 -> 12.
        0x6022, // CodexAstraUlt: str r2, [r4].
        0x6863, // CodexAstraUlt: ldr r3, [r4, #4] reads unchanged data.
        0x2a0c, // CodexAstraUlt: cmp r2, #12 -> Z and C set.
        0xdf2a, // CodexAstraUlt: svc #42.
    ]);
    memory.load(START, &text);
    memory.load(DATA + 4, &0x7fc0_0001u32.to_le_bytes());
    let mut expected_cpu = cpu.clone();
    expected_cpu.regs[0] = 7;
    expected_cpu.regs[1] = 5;
    expected_cpu.regs[2] = 12;
    expected_cpu.regs[3] = 0x7fc0_0001;
    expected_cpu.regs[15] = START + text.len() as u32;
    expected_cpu.cpsr.z = true;
    expected_cpu.cpsr.c = true;
    let mut expected_memory = memory.clone();
    expected_memory.load(DATA, &12u32.to_le_bytes());
    let thumb_case = Fixture {
        name: "thumb_integer_memory",
        text,
        seeds: vec![START | 1],
        expected: Snapshot::capture(&expected_cpu, &expected_memory),
        cpu,
        memory,
        fallback_steps: 0,
        native_budget: 7,
        native_lookups: 0,
        thumb_entry: Some(START | 1),
    };

    let (mut cpu, mut memory) = initial(false);
    cpu.regs[8] = EXTRA;
    let text = arm(&[
        0xe3a0_0007, // CodexAstraUlt: mov r0, #7.
        0xe12f_ff18, // CodexAstraUlt: bx r8, unknown to static discovery.
    ]);
    let absent = arm(&[
        0xe280_0005, // CodexAstraUlt: add r0, r0, #5, reached by fallback.
        0xe584_0000, // CodexAstraUlt: str r0, [r4].
        0xef00_002a, // CodexAstraUlt: svc #42.
    ]);
    memory.load(START, &text);
    memory.load(EXTRA, &absent);
    let mut expected_cpu = cpu.clone();
    expected_cpu.regs[0] = 12;
    expected_cpu.regs[15] = EXTRA + absent.len() as u32;
    let mut expected_memory = memory.clone();
    expected_memory.load(DATA, &12u32.to_le_bytes());
    let missing_case = Fixture {
        name: "arm_missing_entry_fallback",
        text,
        seeds: vec![START],
        expected: Snapshot::capture(&expected_cpu, &expected_memory),
        cpu,
        memory,
        fallback_steps: 3,
        native_budget: 2,
        native_lookups: 0,
        thumb_entry: None,
    };

    let (mut cpu, mut memory) = initial(false);
    let target = START + 0x20;
    cpu.regs[8] = target | 1;
    let mut text = arm(&[
        0xe3a0_0007, // CodexAstraUlt: mov r0, #7.
        0xe12f_ff18, // CodexAstraUlt: bx r8 changes ARM to Thumb.
    ]);
    text.resize(0x20, 0);
    text.extend(thumb(&[
        0x3005, // CodexAstraUlt: adds r0, #5 -> 12, NZCV clear.
        0x6020, // CodexAstraUlt: str r0, [r4].
        0xdf2a, // CodexAstraUlt: svc #42 from Thumb.
    ]));
    memory.load(START, &text);
    let mut expected_cpu = cpu.clone();
    expected_cpu.regs[0] = 12;
    expected_cpu.regs[15] = START + text.len() as u32;
    expected_cpu.cpsr.thumb = true;
    let mut expected_memory = memory.clone();
    expected_memory.load(DATA, &12u32.to_le_bytes());
    let interwork_case = Fixture {
        name: "arm_to_thumb_native",
        text,
        seeds: vec![START, target | 1],
        expected: Snapshot::capture(&expected_cpu, &expected_memory),
        cpu,
        memory,
        fallback_steps: 0,
        native_budget: 5,
        native_lookups: 1,
        thumb_entry: Some(target | 1),
    };
    vec![arm_case, thumb_case, missing_case, interwork_case]
}

// CodexAstraUlt: A real guest infinite loop tests that budget exhaustion cannot
// be reported as a completed equivalence test, even when both snapshots agree.
pub fn endless() -> Fixture {
    let (cpu, mut memory) = initial(false);
    let text = arm(&[0xeaff_fffe]);
    memory.load(START, &text);
    Fixture {
        name: "instruction_limit_negative_control",
        text,
        seeds: vec![START],
        expected: Snapshot::capture(&cpu, &memory),
        cpu,
        memory,
        fallback_steps: 0,
        native_budget: 0,
        native_lookups: 0,
        thumb_entry: None,
    }
}
